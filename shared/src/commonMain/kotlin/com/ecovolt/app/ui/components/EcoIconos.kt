private fun icono(nombre: String, vararg trazos: String): ImageVector = iconoConGrosor(nombre, 2f, *trazos)

private fun iconoConGrosor(nombre: String, grosor: Float, vararg trazos: String): ImageVector {
    val constructor = ImageVector.Builder(
        name = nombre,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f
    )
    for (trazo in trazos) {
        constructor.addPath(
            pathData = PathParser().parsePathString(trazo).toNodes(),
            fill = null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = grosor,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round
        )
    }
    return constructor.build()
}
